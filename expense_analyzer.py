
# Day 1 - Expense Analyzer

# Topic 1: Variables
food = 150
travel = 100
shopping = 500
snacks = 50

# Topic 2: List
expenses = [food, travel, shopping, snacks]

# Topic 3: Total Expenses
total = sum(expenses)

# Topic 4: Highest Expense
highest = max(expenses)

# Topic 5: Lowest Expense
lowest = min(expenses)

# Topic 6: Count Expenses
count = len(expenses)

# Topic 7: Average Expense
average = total / count

# Topic 8: Display Output
print("Total Expenses:", total)
print("Highest Expense:", highest)
print("Lowest Expense:", lowest)
print("Number of Expenses:", count)
print("Average Expense:", average)
